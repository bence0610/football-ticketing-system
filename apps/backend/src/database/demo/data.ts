/** Lower-case ASCII with no accents, for the local part of an e-mail address. */
export function asciiFold(text: string): string {
  return text
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '');
}
